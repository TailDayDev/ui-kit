import type { Meta, StoryObj } from '@storybook/react-native-web-vite';

import { Box, Icon, Text, type IconColor } from '../primitives';
import * as FigmaIcons from './figma';

interface IconGalleryProps {
  color: IconColor;
  size: number;
}

const IconGallery = ({ color, size }: IconGalleryProps) => (
  <Box row gap={4} style={{ flexWrap: 'wrap' }}>
    {Object.entries(FigmaIcons).map(([name, IconSvg]) => (
      <Box key={name} align="center" gap={2} style={{ width: 96 }}>
        <Icon icon={IconSvg} color={color} size={size} />
        <Text variant="smallCaption/regular" color="secondary" align="center">
          {name}
        </Text>
      </Box>
    ))}
  </Box>
);

const meta = {
  title: 'Foundations/Icons',
  component: IconGallery,
  args: { color: 'default' as IconColor, size: 24 },
  argTypes: {
    color: {
      control: 'select',
      options: [
        'default',
        'accent',
        'text.primary',
        'text.error',
        'text.inverse',
      ],
    },
    size: { control: { type: 'range', min: 12, max: 48, step: 2 } },
  },
} satisfies Meta<typeof IconGallery>;

export default meta;
type Story = StoryObj<typeof meta>;

/** The icon set from the Figma page "01 Components" (generated by scripts/figma/build-icons.mjs). */
export const FigmaSet: Story = {};
