#!/usr/bin/env node
/**
 * Generates React Native icon components from the Figma SVG export:
 *   figma/components/svg/<figma-name>.svg  →  src/icons/figma/Icon<PascalName>.tsx
 *
 * Every color in the SVG becomes the `color` prop (icons are single-color in Figma),
 * so callers tint them through the theme (`<Icon icon={IconSearch} color="accent" />`).
 *
 * Usage: node scripts/figma/build-icons.mjs   (after npm run figma:export-components)
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SVG_DIR = join(ROOT, 'figma', 'components', 'svg');
const OUT_DIR = join(ROOT, 'src', 'icons', 'figma');
// Device chrome drawn by the OS, not an app icon.
const SKIP = new Set(['ios-status-indicators']);

const ELEMENTS = {
  path: 'Path',
  rect: 'Rect',
  circle: 'Circle',
  ellipse: 'Ellipse',
  line: 'Line',
  polyline: 'Polyline',
  polygon: 'Polygon',
  g: 'G',
  defs: 'Defs',
  clipPath: 'ClipPath',
  mask: 'Mask',
};
const COLOR_ATTRS = new Set(['fill', 'stroke', 'stop-color']);

const pascal = name =>
  name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('');
const camel = attr => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function convert(svg, componentName, figmaName) {
  const root = svg.match(/<svg([^>]*)>/);
  if (!root) throw new Error(`${figmaName}: no <svg> root`);
  const attr = (source, key) =>
    source.match(new RegExp(`\\s${key}="([^"]*)"`))?.[1];
  const viewBox =
    attr(root[1], 'viewBox') ??
    `0 0 ${attr(root[1], 'width')} ${attr(root[1], 'height')}`;
  const frame = Number(attr(root[1], 'width') ?? viewBox.split(' ')[2]);
  const used = new Set(['Svg']);

  const body = svg
    .slice(root.index + root[0].length, svg.lastIndexOf('</svg>'))
    .replace(
      /<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g,
      (match, closing, tag, attrs, selfClosing) => {
        const component = ELEMENTS[tag];
        if (!component) throw new Error(`${figmaName}: unsupported <${tag}>`);
        used.add(component);
        if (closing) return `</${component}>`;
        const props = [...attrs.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)]
          .map(([, key, value]) => {
            if (
              COLOR_ATTRS.has(key) &&
              value !== 'none' &&
              !value.startsWith('url(')
            ) {
              return `${camel(key)}={color}`;
            }
            if (key === 'id') return `id={\`\${id}-${value}\`}`;
            if (value.startsWith('url(#')) {
              return `${camel(key)}={\`url(#\${id}-${value.slice(5, -1)})\`}`;
            }
            return `${camel(key)}="${value}"`;
          })
          .join(' ');
        return `<${component} ${props}${selfClosing ? ' /' : ''}>`;
      },
    );

  const needsId = body.includes('${id}');
  const imports = [...used].filter(c => c !== 'Svg').sort();
  return `// AUTO-GENERATED by scripts/figma/build-icons.mjs from the Figma icon "${figmaName}".
// Do not edit by hand: update the icon in Figma and re-run the export.
${needsId ? "import { useId } from 'react';\n" : ''}import Svg${imports.length ? `, { ${imports.join(', ')} }` : ''} from 'react-native-svg';

import type { IconComponentProps } from '../../primitives';

/** Figma icon \`${figmaName}\` (${frame}×${frame} frame). Color comes from \`color\`. */
export const ${componentName} = ({
  color,
  size = ${frame},
  width,
  height,
}: IconComponentProps) => {
${needsId ? "  const id = useId().replace(/[^a-zA-Z0-9_-]/g, '');\n" : ''}  return (
    <Svg width={width ?? size} height={height ?? size} viewBox="${viewBox}" fill="none">
      ${body.trim()}
    </Svg>
  );
};
`;
}

if (!existsSync(SVG_DIR)) {
  console.error(`No ${SVG_DIR}. Run npm run figma:export-components first.`);
  process.exit(1);
}
mkdirSync(OUT_DIR, { recursive: true });
const prettierConfig =
  (await prettier.resolveConfig(join(OUT_DIR, 'x.tsx'))) ?? {};
const names = [];
for (const file of readdirSync(SVG_DIR)
  .filter(f => f.endsWith('.svg'))
  .sort()) {
  const figmaName = file.replace(/\.svg$/, '');
  if (SKIP.has(figmaName)) continue;
  const componentName = `Icon${pascal(figmaName.replace(/^tab-icon-/, 'tab-'))}`;
  const source = convert(
    readFileSync(join(SVG_DIR, file), 'utf8'),
    componentName,
    figmaName,
  );
  const filePath = join(OUT_DIR, `${componentName}.tsx`);
  writeFileSync(
    filePath,
    await prettier.format(source, { ...prettierConfig, filepath: filePath }),
  );
  names.push(componentName);
}
const index = `// AUTO-GENERATED by scripts/figma/build-icons.mjs — the Figma icon set.\n${names
  .map(n => `export { ${n} } from './${n}';`)
  .join('\n')}\n`;
writeFileSync(
  join(OUT_DIR, 'index.ts'),
  await prettier.format(index, {
    ...prettierConfig,
    filepath: join(OUT_DIR, 'index.ts'),
  }),
);
console.warn(`Generated ${names.length} icons in src/icons/figma`);
